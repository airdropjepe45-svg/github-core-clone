/** All twelve scenario users, in generation order: [0] is the viewer. */
export const SCENARIO_USERS: readonly ScenarioUser[] = Object.freeze(generateUsers(scenarioRng('users'), 12));

/** The viewer: the token owner every check addresses. Derived, then asserted. */
export const VIEWER_USER: ScenarioUser = SCENARIO_USERS[0] as ScenarioUser;
/** The viewer's teammate (second generated user). */
export const TEAMMATE_USER: ScenarioUser = SCENARIO_USERS[1] as ScenarioUser;
/** The stranger (third generated user). */
export const STRANGER_USER: ScenarioUser = SCENARIO_USERS[2] as ScenarioUser;

if (VIEWER_USER.login !== 'adaiversen') {
  throw new Error(`scenario derivation mismatch: viewer login is ${VIEWER_USER.login}, expected adaiversen`);
}
if (TEAMMATE_USER.login !== 'quinnkeller') {
  throw new Error(`scenario derivation mismatch: teammate login is ${TEAMMATE_USER.login}, expected quinnkeller`);
}
if (STRANGER_USER.login !== 'olgabauer') {
  throw new Error(`scenario derivation mismatch: stranger login is ${STRANGER_USER.login}, expected olgabauer`);
}

