/** The scenario org: `<adjective>-<noun>-org` from the `org` stream. Derived, then asserted. */
export const ORG: string = (() => {
  const orgRng = scenarioRng('org');
  const org = `${orgRng.pick(REPO_ADJECTIVES)}-${orgRng.pick(REPO_NOUNS)}-org`;
  if (org !== 'faint-meadow-org') {
    throw new Error(`scenario derivation mismatch: org is ${org}, expected faint-meadow-org`);
  }
  return org;
})();
